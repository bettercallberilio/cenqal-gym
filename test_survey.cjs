const assert=require('node:assert/strict');
const core=require('./survey-core.js');
const def=require('./survey-instrument-v1.json');
const c={enabled:true,opens_at:'2026-11-30T00:00:00+01:00',closes_at:'2026-12-01T00:00:00+01:00'};
assert.equal(core.windowState(c,Date.parse('2026-11-29T22:59:59Z')),'scheduled');
assert.equal(core.windowState(c,Date.parse('2026-11-29T23:00:00Z')),'open');
assert.equal(core.windowState(c,Date.parse('2026-11-30T22:59:59Z')),'open');
assert.equal(core.windowState(c,Date.parse('2026-11-30T23:00:00Z')),'closed');
assert.equal(core.windowState({...c,enabled:false},Date.parse('2026-11-30T12:00:00Z')),'disabled');
assert.equal(new Set(def.map(q=>q.id)).size,def.length);
assert(core.validate(def,{LEARN01:'NA',OPEN01:'',EMO01:['Motivación','Agobio']}));
assert(core.validate(def,{}));
assert.throws(()=>core.validate(def,{unknown:'1'}));
assert.throws(()=>core.validate(def,{LEARN01:'6'}));
assert.throws(()=>core.validate(def,{OPEN01:'x'.repeat(3001)}));
assert.throws(()=>core.validate(def,{EMO01:['Agobio','Agobio']}));
assert.throws(()=>core.validate(def,{EMO01:['Agobio','Prefiero no responder']}));
const rows=core.summarize(def,[{answers:{LEARN01:'5'}},{answers:{LEARN01:'NA'}},{answers:{}}]);
assert.equal(rows.find(x=>x.variable==='LEARN01'&&x.opcion.startsWith('5')).n_responden,2);
assert.equal(rows.find(x=>x.variable==='LEARN01'&&x.opcion.startsWith('5')).porcentaje,50);
console.log('Survey: date boundaries, missing values, scales, privacy options and summary passed.');
